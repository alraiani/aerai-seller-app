namespace AERai.Web.Domain.Ingestion;

/// <summary>
/// The Amazon data the app ingests automatically, and how each is obtained. Every value but
/// <see cref="AwdInventory"/>, <see cref="OrdersApi"/>, <see cref="DeferredTransactions"/>, and <see cref="AdsSpend"/>
/// is an SP-API Reports API report.
/// </summary>
public enum AmazonReportType
{
    /// <summary>
    /// <c>GET_FLAT_FILE_ALL_ORDERS_DATA_BY_LAST_UPDATE_GENERAL</c>: requested on demand for a time window
    /// (orders created or updated since the last successful run).
    /// </summary>
    Orders = 1,

    /// <summary><c>GET_FBA_MYI_ALL_INVENTORY_DATA</c>: requested on demand; a point-in-time snapshot.</summary>
    FbaInventory = 2,

    /// <summary>
    /// <c>GET_V2_SETTLEMENT_REPORT_DATA_FLAT_FILE_V2</c> (one row per amount): generated by Amazon on its own schedule (it cannot
    /// be requested), so runs list newly available reports and ingest any not seen before.
    /// </summary>
    Settlements = 3,

    /// <summary>
    /// <c>GET_RESERVED_INVENTORY_DATA</c>: requested on demand; a point-in-time snapshot of why stock
    /// is reserved (customer orders, FC transfers, FC processing).
    /// </summary>
    FbaReservedInventory = 4,

    /// <summary>
    /// <c>GET_RESTOCK_INVENTORY_RECOMMENDATIONS_REPORT</c>: requested on demand; a point-in-time snapshot
    /// of how many units Amazon recommends sending in and by when.
    /// </summary>
    RestockRecommendations = 5,

    /// <summary>
    /// AWD inventory (<c>GET /awd/2024-05-09/inventory</c>): not a report but a paginated listing of
    /// what Amazon Warehousing and Distribution holds now; a point-in-time snapshot.
    /// </summary>
    AwdInventory = 6,

    /// <summary>
    /// Orders from the Orders API (<c>GET /orders/2026-01-01/orders</c>, <c>searchOrders</c>): not a report but a
    /// paginated search that returns each order with its line items inline. Written straight to
    /// <c>core.Order</c>/<c>core.OrderItem</c>, so it is fresher than the Orders report but carries no
    /// staging batch.
    /// </summary>
    OrdersApi = 7,

    /// <summary>
    /// Deferred transactions from the Finances API (<c>GET /finances/2024-06-19/transactions</c>,
    /// <c>listTransactions</c>): not a report but a paginated listing of the sales Amazon is still holding
    /// back (its delivery-date policy and invoiced orders), plus those released since the last run. Written
    /// straight to <c>core.DeferredTransaction</c>; a snapshot of what is held now, so it cannot be backfilled.
    /// </summary>
    DeferredTransactions = 8,

    /// <summary>
    /// Sponsored Products spend per SKU and day from the Amazon Ads API (<c>spAdvertisedProduct</c>, reporting v3):
    /// not SP-API but a separate API with its own authorization. Requested on demand for a date range like the
    /// Reports API, then written straight to <c>core.AdSpend</c>, replacing that range.
    /// </summary>
    AdsSpend = 9,

    /// <summary>
    /// <c>GET_FBA_INVENTORY_PLANNING_DATA</c> (Amazon's FBA Inventory / inventory health report): requested on demand;
    /// a point-in-time snapshot of each SKU's stock age, Amazon's estimated excess units, and the storage fees and
    /// aged-inventory surcharge coming.
    /// </summary>
    FbaInventoryPlanning = 10,
}
